"""Generate native identities plus UI presentation; refuse identity mismatches."""
import argparse
import copy
import json
from pathlib import Path
import re
import subprocess
import os

ROOT = Path(__file__).resolve().parents[1]


def source_manifest_index(root):
    paths = sorted((root / 'modules').glob('*/module.json'))
    paths += sorted((root / 'sdk/examples').glob('*/module.json'))
    manifests = {}
    for path in paths:
        manifest = json.loads(path.read_text(encoding='utf-8'))
        identity = manifest['id']
        if identity in manifests:
            raise ValueError(f'duplicate native module ID: {identity}')
        # Manifests contain ABI/schema versions, not the module's saved-data version.
        info = re.search(r'ws::Info\s+info\s*\{\s*"([^"]+)"\s*,\s*"[^"]*"\s*,\s*(\d+)\s*}',
                         path.with_name('dsp.h').read_text(encoding='utf-8'))
        if not info or info[1] != identity or int(info[2]) < 1:
            raise ValueError(f'{path}: descriptor identity/version missing or mismatched')
        manifests[identity] = (manifest, int(info[2]))
    return manifests


def descriptor_index(describe):
    result = subprocess.run([str(Path(describe).resolve())], check=True,
                            capture_output=True, text=True, encoding='utf-8', timeout=30)
    descriptors = {}
    for native in json.loads(result.stdout)['modules']:
        identity = native['id']
        if identity in descriptors:
            raise ValueError(f'duplicate descriptor ID: {identity}')
        native['parameters'] = dict(sorted(native['parameters'].items(), key=lambda item: item[1]))
        descriptors[identity] = (native, native['version'])
    return descriptors


def generate(root=ROOT, descriptors=None):
    presentation = json.loads((root / 'apps/studio/public/catalogue-presentation.json').read_text(encoding='utf-8'))
    # Source-only check remains an independent drift witness for Studio-only jobs.
    manifests = source_manifest_index(root) if descriptors is None else descriptors
    modules = presentation['modules']
    if len({m['id'] for m in modules}) != len(modules) or {m['id'] for m in modules} != set(manifests):
        raise ValueError('module ID mismatch between native catalogue and presentation sidecar')
    result = []
    for original in modules:
        m = copy.deepcopy(original)
        native, version = manifests[m['id']]
        ports = {(p['direction'], p['id']) for p in m['ports']}
        expected = {(direction, key) for direction, field in [('input', 'inputs'), ('output', 'outputs')]
                    for key in native.get(field, {})}
        params = native.get('parameters', {})
        if (ports != expected or len(ports) != len(m['ports'])
                or {p['id'] for p in m['parameters']} != set(params)
                or len(m['parameters']) != len(params)):
            raise ValueError(f"{m['id']}: port/parameter ID mismatch; refusing to rename IDs")
        m['id'], m['name'] = native['id'], native['name']
        m['version'] = version
        m['legacy_parameters'] = params
        for port in m['ports']:
            port['kind'] = native['inputs' if port['direction'] == 'input' else 'outputs'][port['id']]
        result.append(m)
    return json.dumps({'note': presentation['note'], 'modules': result}, indent=1) + '\n'


def known_ids_content(descriptors, existing):
    prior = [line.strip() for line in existing.splitlines()
             if line.strip() and not line.startswith('#')]
    if len(prior) != len(set(prior)) or not set(prior) <= set(descriptors):
        raise ValueError('known module ID removed or duplicated; Architect ruling required')
    return ('# SPDX-License-Identifier: GPL-3.0-only\n'
            '# Generated by tools/gen_ui_catalogue.py from wire-describe; never remove IDs.\n'
            + ''.join(identity + '\n' for identity in sorted(descriptors)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--describe', type=Path,
                        help='path to built wire-describe (required for generation; optional for source-only check)')
    args = parser.parse_args()
    target = ROOT / 'apps/studio/public/wirescape_modules.json'
    fixture = ROOT / 'tools/foundation/fixtures/known_module_ids.txt'
    try:
        describe = args.describe
        if not args.check and describe is None:
            describe = ROOT / 'build/native' / ('wire-describe.exe' if os.name == 'nt' else 'wire-describe')
        native = descriptor_index(describe) if describe is not None else None
        content = generate(descriptors=native)
        known = known_ids_content(native if native is not None else source_manifest_index(ROOT),
                                  fixture.read_text(encoding='utf-8'))
    except (ValueError, KeyError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f'{error}\n')
    if args.check:
        if target.read_text(encoding='utf-8') != content:
            parser.exit(1, 'UI catalogue drift; run python tools/gen_ui_catalogue.py\n')
        if fixture.read_text(encoding='utf-8') != known:
            parser.exit(1, 'known module ID fixture drift; regenerate with wire-describe\n')
        print('UI catalogue and known IDs match ' + ('live descriptors' if native is not None else 'native manifests') + ' and presentation sidecar')
    else:
        target.write_text(content, encoding='utf-8', newline='\n')
        fixture.write_text(known, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
